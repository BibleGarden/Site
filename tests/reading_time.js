'use strict';
const assert = require('node:assert/strict');
const {calculate, calendar, hMM, scopeBooks, date} = require('../static/bible-garden/js/reading-time.js');
const units = {verse:{count:10,seconds:80},paragraph:{count:2,seconds:90},section:{count:1,seconds:95},chapter:{count:1,seconds:98}};
const data={voices:{a:{books:{1:{seconds:100,units}}},b:{books:{1:{seconds:200,units}}}},translations:{t:{books:{1:{words:200}}}}};
const base={mode:'listen',scope:'book',book:1,voice:'a',speed:2,pause_unit:'verse',pause:2,multi:false};
assert.equal(calculate(data,base).total,70);
assert.equal(calculate(data,{...base,speed:1}).pauses,20);
assert.equal(calculate(data,{...base,pause_unit:'none'}).total,50);
assert.equal(calculate(data,{...base,multi:true,voice_b:'b',speed_a:2,speed_b:1,pause_a:2,pause_b:3,unit:'verse'}).total,170);
assert.equal(calculate(data,{...base,mode:'silent',translation:'t',wpm:200}).total,60);
assert.equal(calculate(data,{...base,scope:'nt'}).total,0);
assert.equal(calculate(data,{...base,scope:'bible'}).missing.length,65);
assert.deepEqual(scopeBooks('gospels'),[40,41,42,43]);
assert.deepEqual(scopeBooks('psalms'),[19]);
for (const speed of [.5,1.1,2.1,NaN]) assert.throws(()=>calculate(data,{...base,speed}));
assert.throws(()=>calculate(data,{...base,pause:61}));
assert.throws(()=>calculate(data,{...base,mode:'silent',translation:'t',wpm:0}));
assert.throws(()=>calculate(data,{...base,voice:'missing'}));
assert.throws(()=>scopeBooks('book',67));
assert.equal(calendar(1800,'2024-02-28','daily',10).finish,'2024-03-01');
assert.equal(calendar(1800,'2026-03-28','daily',10).finish,'2026-03-30');
assert.equal(calendar(600,'2026-10-04','deadline','2026-10-04').minutes,10);
assert.equal(calendar(1200,'2026-10-04','deadline','2026-10-05').days,2);
assert.throws(()=>calendar(600,'2026-10-04','deadline','2026-10-03'));
assert.throws(()=>date('2026-02-29'));
assert.throws(()=>calendar(600,'9999-12-31','daily',1));
assert.equal(hMM(3601),'1:01');
